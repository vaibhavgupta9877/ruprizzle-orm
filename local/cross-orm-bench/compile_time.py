#!/usr/bin/env python3
"""Compile-time benchmark for generated ruprizzle clients.

Generates synthetic `schema.ruprizzle` files with 50 and 200 models,
creates a temporary `generated_client` crate in `target/bench-compile/`,
runs `ruprizzle generate`, builds the crate with `cargo build --release`,
and records wall time and binary size in `docs/BenchmarkResults.md`.

Usage:
    python compile_time.py

Override the model counts with the BENCH_COMPILE_MODELS environment variable:
    BENCH_COMPILE_MODELS=2,5 python compile_time.py
"""

import glob
import os
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
BENCH_DIR = REPO_ROOT / "target" / "bench-compile"
CRATE_DIR = BENCH_DIR / "generated_client"
SRC_DIR = CRATE_DIR / "src"
GENERATED_DIR = SRC_DIR / "generated"
DOCS_PATH = REPO_ROOT / "docs" / "BenchmarkResults.md"

MODEL_COUNTS = [
    int(x.strip())
    for x in os.environ.get("BENCH_COMPILE_MODELS", "50,200").split(",")
    if x.strip()
]

SCHEMA_TEMPLATE = """// Synthetic schema for compile-time benchmark ({count} models).
// Generated by compile_time.py; do not edit.

datasource db {{
  provider = "sqlite"
  url      = env("DATABASE_URL")
}}

generator client {{
  output      = "src/generated"
  module_name = "generated"
}}

{models}
"""

MODEL_TEMPLATE = """model Model{idx} {{
  id    BigInt  @id
  name  String
  n     BigInt
  flag  Boolean
  value Float
}}"""


def generate_schema(count: int) -> str:
    models = "\n\n".join(MODEL_TEMPLATE.format(idx=i) for i in range(count))
    return SCHEMA_TEMPLATE.format(count=count, models=models)


def write_crate() -> None:
    CRATE_DIR.mkdir(parents=True, exist_ok=True)
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)

    (CRATE_DIR / "Cargo.toml").write_text(
        """[package]
name = "generated_client"
version = "0.1.0"
edition = "2024"
publish = false

[dependencies]
ruprizzle = { path = "../../../crates/runtime" }
ruprizzle-core = { path = "../../../crates/core" }
# sqlx::FromRow is generated for aggregate structs; the `macros` feature is
# needed for the derive macro even though ruprizzle enables the runtime
# and driver features for the re-exported sqlx crate.
sqlx = { version = "0.8", features = ["macros"] }

[features]
default = []
# The generated code conditionally compiles rusqlite and tokio-postgres
# helpers; defining the features silences rustc unexpected-cfg warnings.
sqlite-rusqlite = []
postgres-tokio-postgres = []
""",
        encoding="utf-8",
    )

    (SRC_DIR / "lib.rs").write_text("pub mod generated;\n", encoding="utf-8")

    (BENCH_DIR / "Cargo.toml").write_text(
        """[workspace]
members = ["generated_client"]
resolver = "3"
""",
        encoding="utf-8",
    )


def run_generate(schema_path: Path) -> None:
    schema_path.write_text(generate_schema(int(schema_path.stem.split("-")[-1])), encoding="utf-8")
    cmd = [
        "cargo",
        "run",
        "--quiet",
        "-p",
        "ruprizzle-cli",
        "--",
        "generate",
        "--schema",
        str(schema_path),
    ]
    subprocess.run(cmd, cwd=REPO_ROOT, check=True)


def build_crate() -> float:
    cmd = [
        "cargo",
        "build",
        "--release",
        "--manifest-path",
        str(BENCH_DIR / "Cargo.toml"),
        "-p",
        "generated_client",
    ]
    start = time.perf_counter()
    subprocess.run(cmd, cwd=REPO_ROOT, check=True)
    return time.perf_counter() - start


def binary_size() -> int:
    target_dir = BENCH_DIR / "target" / "release"
    candidates = [
        p
        for pattern in ("generated_client*", "libgenerated_client*")
        for p in target_dir.glob(pattern)
        if p.is_file() and p.suffix not in {".d", ".pdb", ".exp", ".lib"}
    ]
    if not candidates:
        return 0
    largest = max(candidates, key=lambda p: p.stat().st_size)
    return largest.stat().st_size


def human_size(size_bytes: int) -> str:
    for unit in ["B", "KB", "MB"]:
        if size_bytes < 1024:
            return f"{size_bytes:.1f} {unit}"
        size_bytes /= 1024
    return f"{size_bytes:.1f} GB"


def record_results(results: list[dict]) -> None:
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "",
        "## Compile-time benchmark",
        "",
        f"_Run at {timestamp}_",
        "",
        "| Models | Wall time (s) | Binary size |",
        "|---|---|---|",
    ]
    for r in results:
        lines.append(
            f"| {r['models']} | {r['wall_seconds']:.2f} | {human_size(r['binary_size'])} |"
        )
    lines.append("")

    if not DOCS_PATH.exists():
        DOCS_PATH.write_text("# Cross-ORM benchmark results\n\n", encoding="utf-8")
    with open(DOCS_PATH, "a", encoding="utf-8") as f:
        f.write("\n".join(lines))


def clean_generated() -> None:
    if GENERATED_DIR.exists():
        shutil.rmtree(GENERATED_DIR)
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)


def main() -> int:
    print(f"Compile-time benchmark: model counts = {MODEL_COUNTS}")
    write_crate()

    results = []
    for count in MODEL_COUNTS:
        print(f"\n--- {count} models ---")
        clean_generated()
        schema_path = CRATE_DIR / f"schema-{count}.ruprizzle"
        print("Generating schema...")
        run_generate(schema_path)
        print("Building generated client...")
        wall = build_crate()
        size = binary_size()
        print(f"  {count} models: {wall:.2f}s, {human_size(size)}")
        results.append({"models": count, "wall_seconds": wall, "binary_size": size})

    record_results(results)
    print(f"\nAppended compile-time results to {DOCS_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

//! The `ruprizzle` command-line interface.
//!
//! The command surface is declared in full from P0 so that the shape of the tool
//! is fixed early and the `migrate dev` / `migrate deploy` split — the guard that
//! keeps a prototyping command away from production data — is structural rather
//! than something bolted on later.
//!
//! Subcommands are implemented in P7; see
//! `ProjectPlan/ImplementationPlan/ImplPlan08CliDx.md`. Until then each one exits
//! non-zero with the phase that will deliver it, rather than pretending to work.

#![forbid(unsafe_code)]
#![warn(clippy::pedantic)]

use std::process::ExitCode;

use clap::{Parser, Subcommand};

#[derive(Parser, Debug)]
#[command(
    name = "ruprizzle",
    version,
    about = "A schema-first ORM for Rust",
    long_about = "Write a schema, get typed entities, a query builder that shows you \
                  its SQL, and migrations generated by diffing your schema."
)]
struct Cli {
    /// Path to the schema file.
    #[arg(
        long,
        global = true,
        default_value = "schema.ruprizzle",
        env = "RUPRIZZLE_SCHEMA"
    )]
    schema: String,

    /// Print the resolved configuration and where each value came from.
    #[arg(long, global = true)]
    verbose: bool,

    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand, Debug)]
enum Command {
    /// Scaffold a schema, `.env`, and migrations directory.
    Init {
        /// Which database this project targets.
        #[arg(long, default_value = "postgres")]
        provider: String,
    },

    /// Parse the schema and emit Rust into the generator's output directory.
    Generate {
        /// Regenerate on every change to the schema file.
        #[arg(long)]
        watch: bool,
    },

    /// Parse and validate the schema without writing anything. For CI.
    Validate,

    /// Rewrite the schema file in canonical form.
    Format,

    /// Migration commands.
    #[command(subcommand)]
    Migrate(MigrateCommand),

    /// Direct-to-database commands that bypass migration history.
    #[command(subcommand)]
    Db(DbCommand),
}

#[derive(Subcommand, Debug)]
enum MigrateCommand {
    /// Diff the schema, write a migration, apply it, and regenerate the client.
    ///
    /// The development workflow. Prompts before anything destructive.
    Dev {
        /// Name for the generated migration directory.
        #[arg(long)]
        name: Option<String>,
        /// Permit changes that discard data.
        #[arg(long)]
        accept_data_loss: bool,
        /// Write the migration but do not apply it.
        #[arg(long)]
        create_only: bool,
    },
    /// Apply pending migrations. No diffing, no prompts, no codegen.
    ///
    /// The production and CI workflow.
    Deploy,
    /// Report applied, pending, and drifted state.
    Status,
    /// Record a migration as applied without running it.
    Resolve {
        /// Migration directory name.
        id: String,
    },
    /// Drop everything and replay the migration history. Development only.
    Reset {
        /// Skip the confirmation prompt.
        #[arg(long)]
        force: bool,
    },
}

#[derive(Subcommand, Debug)]
enum DbCommand {
    /// Push the schema straight to the database with no migration file.
    Push {
        /// Permit changes that discard data.
        #[arg(long)]
        accept_data_loss: bool,
    },
    /// Run the project's seed script.
    Seed,
}

/// Which phase delivers a given command, so the message can say so.
fn owning_phase(command: &Command) -> (&'static str, &'static str) {
    match command {
        Command::Generate { .. } | Command::Validate => ("P1-P3", "ImplPlan02SchemaDslParser.md"),
        Command::Migrate(_) | Command::Db(DbCommand::Push { .. }) => {
            ("P6", "ImplPlan07Migrations.md")
        }
        Command::Init { .. } | Command::Format | Command::Db(DbCommand::Seed) => {
            ("P7", "ImplPlan08CliDx.md")
        }
    }
}

fn main() -> ExitCode {
    let cli = Cli::parse();

    if cli.verbose {
        eprintln!("schema path: {}", cli.schema);
    }

    let (phase, doc) = owning_phase(&cli.command);
    eprintln!(
        "ruprizzle: this command is not implemented yet.\n\
         \n\
         The workspace foundation (phase P0) is in place; this command arrives in \
         phase {phase}.\n\
         See ProjectPlan/ImplementationPlan/{doc} for what it will do."
    );
    ExitCode::FAILURE
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::CommandFactory;

    #[test]
    fn cli_definition_is_valid() {
        // Catches conflicting flags, bad defaults, and duplicate names at test
        // time rather than on a user's first run.
        Cli::command().debug_assert();
    }

    #[test]
    fn dev_and_deploy_are_separate_subcommands() {
        // The guard from ImplPlan08: `migrate deploy` must not accept the
        // destructive flags that `migrate dev` does, so habit cannot carry a
        // dangerous invocation into production.
        assert!(Cli::try_parse_from(["ruprizzle", "migrate", "dev", "--accept-data-loss"]).is_ok());
        assert!(
            Cli::try_parse_from(["ruprizzle", "migrate", "deploy", "--accept-data-loss"]).is_err()
        );
    }

    #[test]
    fn schema_path_defaults_and_can_be_overridden() {
        let cli = Cli::try_parse_from(["ruprizzle", "validate"]).unwrap();
        assert_eq!(cli.schema, "schema.ruprizzle");

        let cli =
            Cli::try_parse_from(["ruprizzle", "--schema", "db/app.ruprizzle", "validate"]).unwrap();
        assert_eq!(cli.schema, "db/app.ruprizzle");
    }
}
